"""Generate the app's example images: synthetic low-light versions of openly licensed photos.

    python scripts/make_examples.py     # -> app/examples/*.jpg + app/examples/SOURCES.md

Sources are scikit-image sample images whose own documentation states CC0 or public-domain status
(see SOURCES.md). Low light is simulated deterministically: linearise (gamma 2.2), scale exposure,
optional spatial illumination, Poisson-Gaussian sensor noise, re-apply gamma, quantise to 8-bit JPEG.
"""

from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np
import skimage
from skimage import data

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "app" / "examples"

EXAMPLES = [
    # name, loader, licence statement (from scikit-image docs), exposure, illumination, read noise, photon scale
    ("coffee_dark", "coffee", "CC0 - photographer Rachel Michetti (no copyright restrictions)",
     0.08, "uniform", 0.004, 2000),
    ("chelsea_extremely_dark", "chelsea", "CC0 - photographer Stefan van der Walt (no copyright restrictions)",
     0.025, "uniform", 0.006, 800),
    ("astronaut_uneven_light", "astronaut", "Public domain - NASA (no known copyright restrictions)",
     0.10, "side", 0.004, 1500),
    ("rocket_night_highlights", "rocket", "Public domain - SpaceX photos released into the public domain",
     0.12, "uniform", 0.004, 1500),
]


def illumination(h, w, kind):
    if kind == "side":  # strong left-to-right falloff: one bright side, one very dark side
        x = np.linspace(1.0, 0.08, w, dtype=np.float32)
        return np.tile(x, (h, 1))[..., None]
    return np.ones((h, w, 1), np.float32)


def make(img_u8, exposure, kind, read_noise, photons, seed):
    rng = np.random.default_rng(seed)
    lin = (img_u8.astype(np.float32) / 255.0) ** 2.2
    lin = lin * exposure * illumination(*lin.shape[:2], kind)
    shot = rng.poisson(lin * photons) / photons
    noisy = np.clip(shot + rng.normal(0, read_noise, lin.shape), 0, 1)
    return (np.clip(noisy ** (1 / 2.2), 0, 1) * 255 + 0.5).astype(np.uint8)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for i, (name, loader, licence, exposure, kind, read_noise, photons) in enumerate(EXAMPLES):
        src = getattr(data, loader)()
        low = make(src, exposure, kind, read_noise, photons, seed=i)
        path = OUT / f"{name}.jpg"
        cv2.imwrite(str(path), cv2.cvtColor(low, cv2.COLOR_RGB2BGR), [cv2.IMWRITE_JPEG_QUALITY, 92])
        rows.append(f"| `{path.name}` | `skimage.data.{loader}()` | {licence} | exposure x{exposure}, "
                    f"{kind} illumination, Poisson-Gaussian noise (read sigma {read_noise}) |")
        print("wrote", path)
    (OUT / "SOURCES.md").write_text(
        "# Example image sources\n\n"
        "Synthetic low-light images generated by `scripts/make_examples.py` from scikit-image "
        f"{skimage.__version__} sample data. The licence of each source photo is as stated in the "
        "scikit-image documentation for that image. No dataset images (LOL, LOL-v2) or personal photos "
        "are redistributed.\n\n"
        "| File | Source | Licence of source image | Low-light simulation |\n|---|---|---|---|\n"
        + "\n".join(rows) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
